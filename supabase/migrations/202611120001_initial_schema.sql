create type public.rol_usuario as enum (
  'ESTUDIANTE',
  'ADMINISTRATIVO'
);

create type public.tipo_reporte as enum (
  'PERDIDO',
  'ENCONTRADO'
);

create type public.estado_reporte as enum (
  'PENDIENTE',
  'APROBADO',
  'RECHAZADO',
  'CERRADO'
);

create type public.estado_solicitud_recuperacion as enum (
  'PENDIENTE',
  'APROBADA',
  'RECHAZADA'
);

create table public.usuario (
  id integer generated by default as identity primary key,
  auth_uid uuid unique references auth.users (id) on delete cascade,
  nombre text not null,
  correo_institucional text not null,
  rol public.rol_usuario not null,
  carrera text,
  cargo text,
  constraint usuario_correo_ucb_check
    check (correo_institucional ~* '^[^@]+@ucb\.edu\.bo$'),
  constraint usuario_atributos_rol_check check (
    (rol = 'ESTUDIANTE' and cargo is null)
    or (rol = 'ADMINISTRATIVO' and carrera is null)
  )
);

create unique index usuario_correo_institucional_lower_idx
  on public.usuario (lower(correo_institucional));

create table public.objeto (
  id integer generated by default as identity primary key,
  nombre text not null,
  descripcion text,
  categoria text not null,
  foto text
);

create table public.reporte (
  id integer generated by default as identity primary key,
  tipo public.tipo_reporte not null,
  fecha date not null,
  lugar text not null,
  contacto text not null,
  estado public.estado_reporte not null default 'PENDIENTE',
  motivo_rechazo text,
  fecha_revision date,
  estudiante_id integer not null references public.usuario (id),
  administrativo_id integer references public.usuario (id),
  objeto_id integer not null unique references public.objeto (id)
);

create index reporte_estado_tipo_idx
  on public.reporte (estado, tipo);

create index reporte_estudiante_id_idx
  on public.reporte (estudiante_id);

create table public.solicitud_recuperacion (
  id integer generated by default as identity primary key,
  reporte_id integer not null references public.reporte (id),
  solicitante_id integer not null references public.usuario (id),
  lugar_estimado text not null,
  fecha_estimada date not null,
  caracteristica_privada text not null,
  estado public.estado_solicitud_recuperacion not null default 'PENDIENTE',
  fecha_revision date,
  administrativo_id integer references public.usuario (id)
);

create index solicitud_recuperacion_reporte_id_idx
  on public.solicitud_recuperacion (reporte_id);

create index solicitud_recuperacion_solicitante_id_idx
  on public.solicitud_recuperacion (solicitante_id);

alter table public.usuario enable row level security;
alter table public.objeto enable row level security;
alter table public.reporte enable row level security;
alter table public.solicitud_recuperacion enable row level security;
